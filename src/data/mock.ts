function notes(
  person: string,
  items: (Omit<ContributorNote, "id" | "seen" | "inArchive"> & { inArchive?: boolean })[],
  unseen = 0,
): ContributorNote[] {
  return items.map((item, index) => ({
    title: item.title,
    durationSec: item.durationSec,
    week: item.week,
    id: `${person}-${index + 1}`,
    seen: index >= unseen || Boolean(item.inArchive),
    inArchive: Boolean(item.inArchive),
  }));
}

